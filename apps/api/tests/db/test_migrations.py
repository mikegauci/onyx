"""Migrations apply to an empty database, reverse cleanly and match the models."""

from alembic import command
from sqlalchemy import Engine, create_engine, inspect, text

from app.core.db.registry import RLS_EXEMPT_TABLES, Base
from tests.db.conftest import TemporaryDatabase, alembic_config

EXPECTED_TABLES = {
    "organizations",
    "users",
    "memberships",
    "modules",
    "organization_modules",
    "audit_entries",
    "outbox_events",
}


def _public_tables(engine: Engine) -> set[str]:
    return set(inspect(engine).get_table_names(schema="public"))


def test_upgrade_downgrade_upgrade_round_trip(temporary_database: TemporaryDatabase) -> None:
    with temporary_database() as url:
        config = alembic_config(url)
        engine = create_engine(url)
        try:
            command.upgrade(config, "head")
            assert _public_tables(engine) == EXPECTED_TABLES | {"alembic_version"}

            command.downgrade(config, "base")
            assert _public_tables(engine) == {"alembic_version"}

            command.upgrade(config, "head")
            assert _public_tables(engine) == EXPECTED_TABLES | {"alembic_version"}
        finally:
            engine.dispose()


def test_models_and_migrations_do_not_drift(temporary_database: TemporaryDatabase) -> None:
    with temporary_database() as url:
        config = alembic_config(url)
        command.upgrade(config, "head")
        # Raises AutogenerateDiffsDetected if the models differ from the migrated schema.
        command.check(config)


def test_models_cover_every_expected_table() -> None:
    assert set(Base.metadata.tables) == EXPECTED_TABLES


def test_every_non_exempt_table_has_row_level_security(migrated_engine: Engine) -> None:
    with migrated_engine.connect() as conn:
        rows = conn.execute(
            text(
                "SELECT relname, relrowsecurity FROM pg_class "
                "WHERE relnamespace = 'public'::regnamespace AND relkind = 'r'"
            )
        ).all()
    missing = sorted(name for name, rls in rows if not rls and name not in RLS_EXEMPT_TABLES)
    assert missing == [], f"Tables without row-level security: {missing}"


def test_required_extensions_are_installed(migrated_engine: Engine) -> None:
    with migrated_engine.connect() as conn:
        names = set(conn.execute(text("SELECT extname FROM pg_extension")).scalars())
    assert {"citext", "vector"} <= names


def test_module_catalogue_is_reference_data(migrated_engine: Engine) -> None:
    with migrated_engine.connect() as conn:
        keys = set(conn.execute(text("SELECT key FROM modules")).scalars())
    assert keys == {"crm", "catalogue", "inbox", "quotations", "orders"}
