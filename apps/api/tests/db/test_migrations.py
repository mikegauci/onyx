def test_lead_archive_migration_preserves_existing_leads(
    temporary_database: TemporaryDatabase,
) -> None:
    with temporary_database() as url:
        config = alembic_config(url)
        command.upgrade(config, "0008")
        engine = create_engine(url)
        lead_id = seed_id("lumen-lighting-test:lead:Lobby chandelier replacement")
        try:
            with engine.begin() as conn:
                seed(conn)
            command.upgrade(config, "0009")
            with engine.begin() as conn:
                row = conn.execute(
                    text("SELECT title, status, archived_at FROM crm_leads WHERE id = :id"),
                    {"id": lead_id},
                ).one()
                assert tuple(row) == ("Lobby chandelier replacement", "qualified", None)
                conn.execute(
                    text("UPDATE crm_leads SET archived_at = now() WHERE id = :id"), {"id": lead_id}
                )
            command.downgrade(config, "0008")
            assert "archived_at" not in {
                c["name"] for c in inspect(engine).get_columns("crm_leads")
            }
            with engine.connect() as conn:
                assert (
                    conn.execute(
                        text("SELECT status FROM crm_leads WHERE id = :id"), {"id": lead_id}
                    ).scalar_one()
                    == "qualified"
                )
            command.upgrade(config, "0009")
            with engine.connect() as conn:
                assert (
                    conn.execute(
                        text("SELECT archived_at FROM crm_leads WHERE id = :id"), {"id": lead_id}
                    ).scalar_one()
                    is None
                )
        finally:
            engine.dispose()


